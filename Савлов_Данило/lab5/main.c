#include <stdio.h>

int main(void)
{
    double a, b;

    printf("Введіть перше число: ");
    if (scanf("%lf", &a) != 1) {
        printf("Помилка введення.\n");
        return 1;
    }

    printf("Введіть друге число: ");
    if (scanf("%lf", &b) != 1) {
        printf("Помилка введення.\n");
        return 1;
    }

    /* Порівняння за допомогою оператора «?:» */
    printf("Результат: %s\n",
           a > b ? "перше число більше за друге" :
           a < b ? "перше число менше за друге" :
                   "числа рівні");

    return 0;
}